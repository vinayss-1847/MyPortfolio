-- Analysis queries: same approach as the original course dataset

-- 1. Finding 5 oldest users
SELECT 
	id, 
    username, 
    created_at 
    FROM users 
    ORDER BY created_at 
    LIMIT 5;

-- 2. On Which two days do most users register on
SELECT DAYNAME(created_at) AS week_day, COUNT(*) AS no_of_reg
FROM users
GROUP BY week_day
ORDER BY no_of_reg DESC
LIMIT 2;

-- 3. Users who never posted a photo
SELECT username, COUNT(image_url) AS no_of_posts
FROM users
LEFT JOIN photos ON users.id = photos.user_id
GROUP BY username
HAVING no_of_posts = 0;

-- 4. Most likes on one photo
SELECT username, photo_id, image_url, COUNT(*) AS likes_no
FROM photos
JOIN likes ON photos.id = likes.photo_id
JOIN users ON photos.user_id = users.id
GROUP BY photo_id
ORDER BY likes_no DESC
LIMIT 1;

-- 5. Average user posts
SELECT (SELECT COUNT(*) FROM photos) / (SELECT COUNT(*) FROM users) AS avg_post;

-- 6. Top 5 most used hashtags
SELECT tag_name, COUNT(*) AS used
FROM photo_tags
JOIN tags ON tags.id = photo_tags.tag_id
GROUP BY tag_id
ORDER BY tag_id DESC
LIMIT 5;

-- 7. Finding bots: users who liked all posts
SELECT username, COUNT(*) AS likes_no
FROM users
JOIN likes ON users.id = likes.user_id
GROUP BY username
HAVING likes_no = (SELECT COUNT(*) FROM photos);
